from collections import Counter

def merge_close_bands(bands, min_dx=30):
    """
    bands: list of (x, color)
    returns: list of (x_mean, color, votes)
    """
    merged = []

    for x, color in sorted(bands):
        if not merged:
            merged.append([x, color, 1])
        else:
            last = merged[-1]
            if abs(x - last[0]) < min_dx:
                last[0] = (last[0] * last[2] + x) / (last[2] + 1)
                last[2] += 1
            else:
                merged.append([x, color, 1])

    return merged

def select_final_bands(bands_with_votes, target=5):

    # Sort by vote strength
    bands_sorted = sorted(bands_with_votes, key=lambda b: b[2], reverse=True)

    # Keep only strongest candidates
    bands_sorted = bands_sorted[:max(target, len(bands_sorted))]

    # Re-sort left → right
    bands_sorted = sorted(bands_sorted, key=lambda b: b[0])

    colors = [b[1] for b in bands_sorted]

    # Force tolerance band to the end if present
    for tol in ['gold', 'silver']:
        if tol in colors:
            colors.remove(tol)
            colors.append(tol)
            break

    return colors[:target]

def calculate_resistance(colors):
    if len(colors) == 5:
        d1, d2, d3, mult, tol = colors
        value = (DIGITS[d1]*100 + DIGITS[d2]*10 + DIGITS[d3]) * MULTIPLIER[mult]
        tolerance = TOLERANCE.get(tol, 'unknown')
        return f"{value:.2g} Ω {tolerance}"

    elif len(colors) == 4:
        d1, d2, mult, tol = colors
        value = (DIGITS[d1]*10 + DIGITS[d2]) * MULTIPLIER[mult]
        tolerance = TOLERANCE.get(tol, 'unknown')
        return f"{value:.2g} Ω {tolerance}"

    else:
        return "Unreliable detection"

DIGITS = {
    'black':0, 'brown':1, 'red':2, 'orange':3,
    'yellow':4, 'green':5, 'blue':6,
    'violet':7, 'grey':8, 'white':9
}

MULTIPLIER = {
    'black':1, 'brown':10, 'red':100, 'orange':1_000,
    'yellow':10_000, 'green':100_000, 'blue':1_000_000,
    'violet':10_000_000, 'gold':0.1, 'silver':0.01
}

TOLERANCE = {
    'brown':'±1%', 'red':'±2%', 'green':'±0.5%',
    'blue':'±0.25%', 'violet':'±0.1%',
    'gold':'±5%', 'silver':'±10%'
}

for filename in os.listdir(UNKNOWN_TEST_DIR):
    if not filename.lower().endswith(('.jpg', '.png', '.jpeg')):
        continue

    image_path = os.path.join(UNKNOWN_TEST_DIR, filename)

    img_bgr = cv2.imread(image_path)
    if img_bgr is None:
        print(f"{filename}: failed to load")
        continue

    resistor_crop = crop_resistor(img_bgr)

    if resistor_crop.size == 0:
        print(f"{filename}: empty crop")
        continue

    hsv = cv2.cvtColor(resistor_crop, cv2.COLOR_BGR2HSV)

    bands = []

    for color, (lower, upper) in COLOR_RANGES.items():
        if color == 'red':
          mask1 = cv2.inRange(hsv, (0, 70, 50), (10, 255, 255))
          mask2 = cv2.inRange(hsv, (170, 70, 50), (180, 255, 255))
          mask = cv2.bitwise_or(mask1, mask2)
        else:
          mask = cv2.inRange(hsv, np.array(lower), np.array(upper))

        kernel = np.ones((3,3), np.uint8)
        mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)
        mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, kernel)

        contours, _ = cv2.findContours(
            mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        for c in contours:
            x, y, w, h = cv2.boundingRect(c)
            if 0.1 * resistor_crop.shape[0] < h < 0.9 * resistor_crop.shape[0] and w < 0.5 * resistor_crop.shape[1]:
                bands.append((x, color))


    print(f"{filename}: Detected bands ->", bands)

    merged = merge_close_bands(bands)

    final_colors = select_final_bands(merged, target=5)
    result = calculate_resistance(final_colors)

    print(f"{filename}: Final bands -> {final_colors}")
    print(f"{filename}: Resistor value =", result)

    cv2_imshow(resistor_crop)

