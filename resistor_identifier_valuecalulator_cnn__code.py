def cnn_resistor_present(image_path, model):
    img = tf.keras.utils.load_img(image_path, target_size=(128,128))
    img = tf.keras.utils.img_to_array(img) / 255.0
    img = tf.expand_dims(img, 0)

    prob_no_resistor = model.predict(img, verbose=0)[0][0]

    resistor_confidence = 1.0 - prob_no_resistor
    resistor_present = resistor_confidence > 0.5

    return resistor_present, resistor_confidence



